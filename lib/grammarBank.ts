// Draw up to `count` entries not in `avoid` (matched on singular OR plural), shuffled.
export function drawPlurals(count: number, avoid: string[] = []): PluralEntry[] {
  const avoidSet = new Set(avoid.map((a) => a.toLowerCase().trim()));
  const pool = FRENCH_PLURAL_NOUNS.filter(
    (e) => !avoidSet.has(e.plural.toLowerCase()) && !avoidSet.has(e.singular.toLowerCase())
  );
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, count);
}
